REMNOTE_TEXT = """🃏 *RemNote — полный гайд*

*Что это?* Приложение для создания карточек с интервальным повторением.
Система сама решает когда показать карточку, чтобы ты не забыл.

*🟢 Когда создавать карточки:*
→ Сразу после урока, пока тема свежа (не во время!)
→ Когда понял новую концепцию, синтаксис, паттерн
→ Когда нашёл и исправил баг (запомни решение!)

*🔁 Когда повторять:*
→ Каждое утро, 10-15 минут, ДО начала новой учёбы
→ RemNote покажет только те карточки, которым "пора"
→ Не пропускай — система ломается если пропускать

*📝 Как писать хорошие карточки:*
❌ Плохо: "Что такое рекурсия?" → "Функция вызывает саму себя"
✅ Хорошо: "Напиши рекурсивный факториал" → def f(n): return 1 if n<=1 else n*f(n-1)

❌ Плохо: копировать текст из учебника
✅ Хорошо: своими словами + пример который ты сам написал

*🎯 Что вносить в карточки (для программирования):*
  • Синтаксис (как написать цикл, функцию, класс)
  • Паттерны решения задач
  • Встроенные функции и методы
  • Ошибки которые долго искал
  • Концепции (что такое замыкание, декоратор, etc.)

*⏱ Норма в день:*
  Новичок: 3-5 новых карточек + повторение старых
  Не гонись за количеством — качество важнее

Планируй RemNote в боте → «📋 План на день» → 🃏 RemNote карточки"""


ANTIBURN_TEXT = """🔥 *Как не выгореть — студенту-программисту*

Выгорание — главная причина бросить программирование.
Вот как его избежать с научным подходом:

*😴 Сон 7-9 часов — не опция*
Мозг консолидирует код во сне. Недосып = медленнее учишься,
больше ошибок, меньше энергии. Это не экономия времени.

*📋 Метод трёх планов:*
  • Минимум: хотя бы 30 минут кода. Не ноль.
  • Средний: обычная норма 2-4 часа.
  • Максимум: когда есть кураж (но не каждый день!)

*⏱ Помодоро для кода:*
  25 мин фокуса → 5 мин отдыха (не телефон!)
  После 4 помодоро → 20-30 мин полноценного отдыха
  Работает потому что создаёт ощущение прогресса.

*🏃 Спорт = топливо для мозга*
2-3 раза в неделю. После тренировки концентрация
заметно выше — это биохимия, не самовнушение.

*🗓 Выходной — обязателен*
Один день в неделю без кода и учёбы.
Мозгу нужно переработать и восстановиться.
Парадоксально, но выходной ускоряет прогресс.

*🧠 Психология прогресса:*
  • Сравнивай себя только с собой вчера
  • Прогресс нелинейный: плато → резкий скачок
  • Каждый день — одна маленькая победа в коде
  • Ошибки = обучение, не провал

*📵 Телефон утром:*
Первые 20 минут после пробуждения — без телефона.
Это реально влияет на концентрацию весь день.

Отслеживай своё состояние в боте — 
«🌅 Утренний опрос» и «🌙 Вечерний дневник»"""


async def guide_handler(update: Update, ctx) -> None:
    await update.message.reply_text(
        GUIDE_TEXT,
        parse_mode="Markdown",
        reply_markup=main_kb()
    )


async def remnote_handler(update: Update, ctx) -> None:
    await update.message.reply_text(
        REMNOTE_TEXT,
        parse_mode="Markdown",
        reply_markup=main_kb()
    )


async def antiburn_handler(update: Update, ctx) -> None:
    await update.message.reply_text(
        ANTIBURN_TEXT,
        parse_mode="Markdown",
        reply_markup=main_kb()
    )
